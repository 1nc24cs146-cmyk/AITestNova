// Pure test-generation logic for AITestNova. No vscode import, so it can be
// smoke-tested with plain Node. Generated tests are templates with real
// cases (normal, empty, null, error) — the user reviews them before saving.
// They are NOT copied from Keploy; they are original templates.

export interface ParsedFunction { name: string; params: string[]; line: number; language: string; }

export function languageFromFile(fileName: string): string {
  if (/\.(ts|tsx|js|jsx|mjs|cjs)$/.test(fileName)) { return 'javascript'; }
  if (/\.py$/.test(fileName)) { return 'python'; }
  if (/\.java$/.test(fileName)) { return 'java'; }
  if (/\.go$/.test(fileName)) { return 'go'; }
  return 'javascript';
}

export function parseFunctions(text: string, language: string): ParsedFunction[] {
  const out: ParsedFunction[] = [];
  const lines = text.split(/\r?\n/);
  const push = (name: string, paramsText: string, line: number) => {
    if (!name || /^(if|for|while|switch|catch|return)$/.test(name)) { return; }
    const params = paramsText.split(',').map((p) => p.trim()).filter(Boolean)
      .map((p) => p.replace(/[:=].*$/, '').replace(/^\*+/, '').replace(/[^A-Za-z0-9_]/g, '')).filter(Boolean);
    if (!out.some((f) => f.name === name && f.line === line)) {
      out.push({ name, params, line, language });
    }
  };
  lines.forEach((line, i) => {
    let m: RegExpExecArray | null;
    if (language === 'python') {
      m = /^\s*def\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(([^)]*)\)/.exec(line);
      if (m) { push(m[1], m[2].replace(/self\s*,?\s*/, ''), i); }
    } else if (language === 'java') {
      m = /(?:public|private|protected|static|\s)+[\w<>\[\]]+\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(([^)]*)\)\s*(?:throws[^{]*)?\{/.exec(line);
      if (m) { push(m[1], m[2], i); }
    } else if (language === 'go') {
      m = /^\s*func\s+(?:\([^)]*\)\s*)?([A-Za-z_][A-Za-z0-9_]*)\s*\(([^)]*)\)/.exec(line);
      if (m) { push(m[1], m[2], i); }
    } else {
      m = /(?:export\s+)?(?:async\s+)?function\s+([A-Za-z_][A-Za-z0-9_$]*)\s*\(([^)]*)\)/.exec(line)
        || /(?:const|let|var)\s+([A-Za-z_][A-Za-z0-9_$]*)\s*=\s*(?:async\s*)?\(([^)]*)\)\s*=>/.exec(line)
        || /^\s*([A-Za-z_][A-Za-z0-9_$]*)\s*\(([^)]*)\)\s*\{/.exec(line);
      if (m) { push(m[1], m[2], i); }
    }
  });
  return out;
}

function sampleValue(param: string): string {
  const p = param.toLowerCase();
  if (/(count|num|age|qty|quantity|amount|price|total|index)/.test(p)) { return '2'; }
  if (/(name|title|email|text|msg|message|str|string)/.test(p)) { return '"hello"'; }
  if (/(flag|enabled|active|valid|is)/.test(p)) { return 'true'; }
  if (/(list|arr|items|data)/.test(p)) { return '[1, 2]'; }
  return '1';
}

export function testFileName(sourceFile: string, language: string): string {
  const base = sourceFile.replace(/\.[^.]+$/, '');
  if (language === 'python') { return `test_${base.split('/').pop()}.py`; }
  if (language === 'java') { return `${base}Test.java`; }
  if (language === 'go') { return `${base}_test.go`; }
  return `${base}.test.${sourceFile.split('.').pop() === 'ts' || sourceFile.endsWith('.tsx') ? 'ts' : 'js'}`;
}

export function generateTestFor(fn: ParsedFunction, sourceFile: string, extraPrompt = '', javaFramework = 'junit'): string {
  const args = fn.params.map(sampleValue).join(', ');
  const call = `${fn.name}(${args})`;
  const extra = extraPrompt.trim()
    ? `\n  // Extra case requested by the user: ${extraPrompt.trim().replace(/\n/g, ' ')}\n`
    : '';
  if (fn.language === 'python') {
    return `# Generated by AITestNova for ${fn.name} in ${sourceFile}\n# Review and edit before committing. Mock external calls as needed.\nimport pytest\nfrom ${sourceFile.replace(/\.py$/, '').split('/').pop()} import ${fn.name}\n\n\ndef test_${fn.name}_normal():\n    result = ${call}\n    assert result is not None\n\n\ndef test_${fn.name}_empty_and_none():\n    for value in ([], "", None):\n        try:\n            ${fn.name}(*([value] * ${Math.max(fn.params.length, 1)}))\n        except (TypeError, ValueError):\n            pass\n${extra}`;
  }
  if (fn.language === 'java') {
    if (javaFramework === 'testng') {
      return `// Generated by AITestNova for ${fn.name} in ${sourceFile}\n// Review and edit before committing. Mock dependencies as needed.\nimport org.testng.annotations.Test;\nimport static org.testng.Assert.*;\n\npublic class ${fn.name}Test {\n  @Test public void normal() {\n    var result = ${call};\n    assertNotNull(result);\n  }\n  @Test public void edgeCases() {\n    ${fn.name}(${fn.params.map(() => 'null').join(', ')});\n  }\n${extra}}\n`;
    }
    return `// Generated by AITestNova for ${fn.name} in ${sourceFile}\n// Review and edit before committing. Mock dependencies as needed.\nimport org.junit.jupiter.api.Test;\nimport static org.junit.jupiter.api.Assertions.*;\n\nclass ${fn.name}Test {\n  @Test void normal() {\n    var result = ${call};\n    assertNotNull(result);\n  }\n  @Test void edgeCases() {\n    assertDoesNotThrow(() -> ${fn.name}(${fn.params.map(() => 'null').join(', ')}));\n  }\n${extra}}\n`;
  }
  if (fn.language === 'go') {
    return `// Generated by AITestNova for ${fn.name} in ${sourceFile}\n// Review and edit before committing. Mock dependencies as needed.\npackage main\n\nimport "testing"\n\nfunc Test${fn.name[0].toUpperCase()}${fn.name.slice(1)}_Normal(t *testing.T) {\n  got := ${call}\n  _ = got\n}\n\nfunc Test${fn.name[0].toUpperCase()}${fn.name.slice(1)}_Edge(t *testing.T) {\n  defer func() { _ = recover() }()\n  _ = ${fn.name}(${fn.params.map(() => 'nil').join(', ')})\n}\n${extra}`;
  }
  return `// Generated by AITestNova for ${fn.name} in ${sourceFile}\n// Review and edit before committing. Mock dependencies as needed.\nimport { ${fn.name} } from './${sourceFile.split('/').pop()}';\n\ndescribe('${fn.name}', () => {\n  test('normal case', () => {\n    const result = ${call};\n    expect(result).not.toBeNull();\n  });\n  test('edge cases', () => {\n    expect(() => ${fn.name}(${fn.params.map(() => 'null').join(', ')})).not.toThrow();\n    expect(() => ${fn.name}(${fn.params.map(() => 'undefined').join(', ')})).not.toThrow();\n  });\n${extra}});\n`;
}

export function generateTestsForFile(text: string, sourceFile: string, extraPrompt = '', javaFramework = 'junit'): string {
  const lang = languageFromFile(sourceFile);
  const fns = parseFunctions(text, lang);
  if (fns.length === 0) { return `// AITestNova: no functions found in ${sourceFile}.\n`; }
  return fns.map((f) => generateTestFor(f, sourceFile, extraPrompt, javaFramework)).join('\n');
}

export function coverageDelta(baseline: number, current: number): { delta: number; improved: boolean } {
  const delta = Math.round((current - baseline) * 10) / 10;
  return { delta, improved: delta > 0 };
}

// Coverage: read the coverage files tools already produce, never invent numbers.
export function parseCoverageXml(xml: string): { lineRate: number; branchRate: number } | null {
  const line = /line-rate="([0-9.]+)"/.exec(xml);
  const branch = /branch-rate="([0-9.]+)"/.exec(xml);
  if (!line) { return null; }
  return { lineRate: Math.round(parseFloat(line[1]) * 1000) / 10, branchRate: branch ? Math.round(parseFloat(branch[1]) * 1000) / 10 : 0 };
}

export function parseJestCoverageJson(jsonText: string): { pct: number } | null {
  try {
    const data = JSON.parse(jsonText) as { total?: { lines?: { pct?: number } } };
    if (typeof data.total?.lines?.pct === 'number') { return { pct: data.total.lines.pct }; }
  } catch { /* not jest coverage */ }
  return null;
}
