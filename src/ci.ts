// Pure CI workflow generation for AITestNova. No vscode import.
export type Stack = 'node' | 'python' | 'go' | 'java' | 'unknown';
export function detectStack(files: string[]): Stack {
  if (files.includes('package.json')) { return 'node'; }
  if (files.includes('go.mod')) { return 'go'; }
  if (files.includes('pom.xml') || files.includes('build.gradle')) { return 'java'; }
  if (files.includes('requirements.txt') || files.includes('pyproject.toml')) { return 'python'; }
  return 'unknown';
}
// testCommand overrides the stack's default test step when the user set
// aitestnova.testCommand — the same setting mutation and unit stability
// already respect, so CI runs exactly the command the user runs locally.
// Every workflow also uploads the coverage output as an artifact, so the
// per-file coverage the Health tab reads is available from a CI run too.
export function generateCIWorkflow(stack: Stack, testCommand?: string): string {
  const steps: Record<Stack, string> = {
    node: '      - uses: actions/setup-node@v4\n        with:\n          node-version: 20\n      - run: npm ci\n      - run: npm test -- --coverage',
    python: '      - uses: actions/setup-python@v5\n        with:\n          python-version: "3.12"\n      - run: pip install -r requirements.txt\n      - run: pytest --cov=. --cov-report=xml',
    go: '      - uses: actions/setup-go@v5\n        with:\n          go-version: "1.22"\n      - run: go test ./... -coverprofile=coverage.out',
    java: '      - uses: actions/setup-java@v4\n        with:\n          java-version: 17\n          distribution: temurin\n      - run: mvn -B test',
    unknown: '      # AITestNova could not detect your stack. Replace this step\n      # with your own test command, e.g. npm test or pytest.\n      - run: echo "Add your test command here"',
  };
  const testStep = testCommand?.trim()
    ? `      - run: ${testCommand.trim()}`
    : steps[stack];
  // With an explicit test command there is no stack to set up — the
  // command is the user's own, and guessing a runtime for it would be
  // wrong as often as right. With a detected stack, the setup step from
  // the stack table runs first.
  const stepsText = testCommand?.trim()
    ? `      - uses: actions/checkout@v4\n${testStep}`
    : `      - uses: actions/checkout@v4\n${steps[stack]}`;
  return `# Generated by AITestNova — review before committing.\n# Runs your tests (with coverage where the stack supports it) on every push/PR.\nname: AITestNova Tests\non: [push, pull_request, workflow_dispatch]\njobs:\n  test:\n    runs-on: ubuntu-latest\n    steps:\n${stepsText}\n      - uses: actions/upload-artifact@v4\n        if: always()\n        with:\n          name: coverage\n          path: |\n            coverage/\n            coverage.out\n          if-no-files-found: ignore\n`;
}
